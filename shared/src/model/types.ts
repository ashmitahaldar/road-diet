export type ElementId =
  | 'sidewalk'
  | 'bike_painted'
  | 'bike_protected'
  | 'bus_lane'
  | 'car_lane'
  | 'parking'
  | 'loading'
  | 'planter'
  | 'patio'

export type Layout = { elements: { id: ElementId; widthM: number }[] }

export type Mode = 'car' | 'bus' | 'bike' | 'walk'

/** Persons/hour on the corridor at peak. */
export type Demand = Record<Mode, number>

export type PersonaId =
  | 'driver_delivery'
  | 'student_cyclist'
  | 'senior_walker'
  | 'shop_owner'

export type Metrics = {
  emissionsKgPerHour: number
  /** vs baseline layout */
  emissionsReductionPct: number
  /** 0-100 */
  safetyScore: number
  travelTimeMin: Record<PersonaId, number>
  /** 0-100 */
  happiness: Record<PersonaId, number>
  /** min happiness */
  fairness: number
  /** max - min happiness, for the debrief */
  fairnessSpread: number
  unusedWidthM: number
}

export type ElementDef = {
  id: ElementId
  label: string
  defaultW: number
  minW: number
  maxW: number
  modes: Mode[]
  /** Persons/hour at defaultW for the modes it serves. */
  capacityPph: number
  source: string
}

/** A model constant and where its value comes from (or TODO-SOURCE). */
export type Sourced<T> = { value: T; source: string }

export type BikeFacility = 'none' | 'painted' | 'protected'

export type Persona = {
  id: PersonaId
  name: string
  blurb: string
  /** Their request in the story, in their own words. Talks about trips, never lane types (spec 2.7). */
  ask: string
  /** What they care about, in a few words, for their card. */
  wants: string
  trip: { mode: Mode; distanceKm: number }
  /** Relative weights over normalized 0-1 metrics (spec 3.7). */
  weights: { travelTime: number; safety: number; comfort: number; access: number }
  baselineHappiness: number
}

export type DataSource = { label: string; url: string; retrieved: string; note: string }

/** Matches the corridor JSON schema (spec 4.4). */
export type Corridor = {
  id: string
  name: string
  widthM: number
  lengthKm: number
  baselineLayout: Layout
  baselineDemand: Demand
  baselineSafety: { ksiCollisions5y: number; pedestrianInvolved: number; cyclistInvolved: number }
  freeFlowSpeedKph: number
  sources: DataSource[]
  /** Generated by data/prep (prep.py map), with its text alternative. */
  mapSvg?: string
  mapAlt?: string
  /** Inputs not taken from a verified dataset (spec 4.5); shown on the limitations panel and /data. */
  estimates?: { field: string; note: string }[]
  /** The raw count behind baselineDemand (prep.py corridor), shown on the About page. */
  observed?: { count: { location_name: string; latest_count_date: string; count_duration: string; total_vehicle: number; total_bike: number; total_pedestrian: number } }
  source: string
}

export type Level = {
  id: string
  name: string
  corridor: Corridor
  allowedElements: ElementId[]
  goal: { minEmissionsReductionPct?: number; minHappiness?: number; minSafety?: number }
  /** 2 stars: goal + safetyScore >= safety; 3 stars: also fairness >= fairness (spec 2.6). */
  stars: { safety: number; fairness: number }
}

/** GET /api/stats/:levelId — how other players solved a level (spec 7, #18). */
export type LevelStats = {
  plays: number
  /** Seeded demo runs included in `plays`; the UI says so. */
  demoPlays: number
  avgStars: number | null
  avgEmissionsReductionPct: number | null
  /** Runs with 0, 1, 2 and 3 stars. */
  starCounts: [number, number, number, number]
  /** Most common element mix (element counts) over recent runs. */
  topMix: { elements: Partial<Record<ElementId, number>>; plays: number } | null
}
